#!/usr/bin/env python3
# writes the key binding tables in README.md from the binding table in src/keymap.c, so the
# readme lists exactly what ctrl+h shows.
#
# usage: tools/bindings.py
#
# the tables go between the "bindings start" and "bindings end" comments in README.md, one
# table per group of bindings (the comments in keymapBindings).

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEYMAP = os.path.join(ROOT, "src", "keymap.c")
README = os.path.join(ROOT, "README.md")
START = "<!-- bindings start: generated by tools/bindings.py -->"
END = "<!-- bindings end -->"

KEY_NAMES = {
    "KeyUp": "Up",
    "KeyDown": "Down",
    "KeyLeft": "Left",
    "KeyRight": "Right",
    "KeyHome": "Home",
    "KeyEnd": "End",
    "KeyPageUp": "PgUp",
    "KeyPageDown": "PgDn",
    "KeyEscape": "Esc",
    "KeyEnter": "Enter",
    "KeyTab": "Tab",
    "KeyBackspace": "Backspace",
    "KeyDelete": "Delete",
    "KeyInsert": "Insert",
    "KeySpace": "Space",
}

# modifiers in the order ctrl+h names them.
MODIFIERS = [("control", "Ctrl"), ("alt", "Alt"), ("shift", "Shift")]

BINDING = re.compile(
    r"\{\s*\{\s*(?P<key>Key\w+|'[^']+')\s*,\s*(?P<modifiers>[^}]*)\}\s*,"
    r"\s*Command\w+\s*,\s*\"(?P<help>[^\"]*)\"\s*\}"
)
GROUP = re.compile(r"^\s*// (?P<name>.+)\.$")


def key_name(key, modifiers):
    parts = [label for name, label in MODIFIERS if re.search(r"\b" + name + r"\b", modifiers)]

    if key.startswith("'"):
        character = key[1:-1].replace("\\\\", "\\")
        parts.append(character.upper() if character.isalpha() else character)
    else:
        parts.append(KEY_NAMES[key])

    return "-".join(parts)


def read_groups():
    source = open(KEYMAP).read()
    table = source[source.index("keymapBindings[] = {"):source.index("};")]
    groups = []
    pending = ""

    # bindings are read across line breaks, since long ones span several lines.
    for line in table.split("\n"):
        group = GROUP.match(line)

        if group:
            groups.append((group.group("name"), []))
            continue

        pending += " " + line.strip()

        for binding in BINDING.finditer(pending):
            name = key_name(binding.group("key"), binding.group("modifiers"))
            groups[-1][1].append((name, binding.group("help")))
            pending = pending[binding.end():]

    return groups


def tables(groups):
    lines = []

    for name, bindings in groups:
        lines += ["", "**" + name[0].upper() + name[1:] + "**", "", "| Key | Action |", "|---|---|"]
        lines += ["| " + key + " | " + text.replace("|", "\\|") + " |" for key, text in bindings]

    return "\n".join(lines) + "\n"


def main():
    readme = open(README).read()

    if START not in readme or END not in readme:
        sys.exit("bindings: README.md has no bindings comments")

    head = readme[:readme.index(START) + len(START)]
    tail = readme[readme.index(END):]
    open(README, "w").write(head + "\n" + tables(read_groups()) + "\n" + tail)


main()
